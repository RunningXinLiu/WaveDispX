function [cases,metrics_table]=analyze_passive_source_convergence( ...
    results_input,source_counts,varargin)
%ANALYZE_PASSIVE_SOURCE_CONVERGENCE Reprocess nested source ensembles.

p=inputParser;
addParameter(p,'OutputFolder','',@(x) ischar(x) || isstring(x));
addParameter(p,'ModeTolerance',15, ...
    @(x) isscalar(x) && isfinite(x) && x>0);
addParameter(p,'DistanceTaperFraction',0.5, ...
    @(x) isscalar(x) && isfinite(x) && x>=0 && x<=1);
parse(p,varargin{:});
opts=p.Results;

if ischar(results_input) || isstring(results_input)
    loaded=load(char(results_input),'results');
    results=loaded.results;
else
    results=results_input;
end
source_counts=reshape(source_counts,1,[]);
available_source_count=size(results.single_source.z,3);
if any(source_counts<1) || any(fix(source_counts)~=source_counts) || ...
        any(source_counts>available_source_count) || ...
        any(diff(source_counts)<=0)
    error('analyze_passive_source_convergence:InvalidSourceCounts', ...
        'SourceCounts must increase from 1 to the available source count.');
end

if strlength(string(opts.OutputFolder))==0
    output_folder=results.output_folder;
else
    output_folder=char(opts.OutputFolder);
end
if ~exist(output_folder,'dir')
    mkdir(output_folder);
end

velocity=results.velocity;
frequency_range=results.reliable_frequency_range_hz;
dispersion_fmax=min(results.source.maxfre, ...
    0.95*results.spatial_alias_limit_hz);
cases=repmat(struct,1,numel(source_counts));
for case_index=1:numel(source_counts)
    source_count=source_counts(case_index);
    if source_count==available_source_count
        gather=results.ncf_gather;
        lag_time=results.lag_time;
        distances=results.distances;
        pair_counts=results.pair_counts;
    else
        source_index=round(linspace(1,available_source_count+1, ...
            source_count+1));
        source_index=source_index(1:end-1);
        [gather,lag_time,distances,pair_counts]= ...
            compute_source_separated_ncf_gather( ...
            results.single_source.z(:,:,source_index), ...
            results.geometry.rx,results.source.dt, ...
            'MaxLag',results.max_lag,'Branch','symmetric', ...
            'DistanceBin',results.geometry.receiver_spacing, ...
            'SpectrumNormalization','phase','WaterLevel',0, ...
            'Algorithm','linear-fft');
    end
    [energy,frequency]=surface_wave_dispersion( ...
        gather,distances,results.source.dt,velocity,dispersion_fmax, ...
        'Method','phase','Component','vertical','FrequencyMin',1, ...
        'ZeroPadding',8,'DistanceTaperFraction', ...
        opts.DistanceTaperFraction,'Plot',false);
    image_metrics=dispersion_image_quality_metrics( ...
        energy,frequency,velocity,results.theory.frequency, ...
        results.theory.rayleigh(:,1),'FrequencyRange',frequency_range);
    sidelobe_metrics=dispersion_sidelobe_metrics( ...
        energy,frequency,velocity,results.theory.frequency, ...
        results.theory.rayleigh,'FrequencyRange',frequency_range, ...
        'ModeTolerance',opts.ModeTolerance);
    cases(case_index).source_count=source_count;
    cases(case_index).source_index=source_index_for_case( ...
        source_count,available_source_count);
    cases(case_index).gather=gather;
    cases(case_index).lag_time=lag_time;
    cases(case_index).distances=distances;
    cases(case_index).pair_counts=pair_counts;
    cases(case_index).energy=energy;
    cases(case_index).frequency=frequency;
    cases(case_index).metrics=image_metrics;
    cases(case_index).sidelobe_metrics=sidelobe_metrics;
end

reference_energy=cases(end).energy;
reference_frequency=cases(end).frequency;
selected=reference_frequency>=frequency_range(1) & ...
    reference_frequency<=frequency_range(2);
for case_index=1:numel(cases)
    if ~isequal(cases(case_index).frequency,reference_frequency)
        error('analyze_passive_source_convergence:FrequencyMismatch', ...
            'All cases must use an identical frequency grid.');
    end
    difference=cases(case_index).energy(:,selected)- ...
        reference_energy(:,selected);
    cases(case_index).relative_l2_to_largest=norm(difference,'fro')/ ...
        max(norm(reference_energy(:,selected),'fro'),eps);
    cases(case_index).mean_absolute_change_to_largest= ...
        mean(abs(difference),'all');
end

metrics_table=table( ...
    [cases.source_count].', ...
    arrayfun(@(x) x.metrics.dominant_ridge_fraction,cases).', ...
    arrayfun(@(x) x.metrics.median_ridge_concentration,cases).', ...
    arrayfun(@(x) x.metrics.median_half_power_width_mps,cases).', ...
    arrayfun(@(x) x.metrics.p10_dominance_margin,cases).', ...
    arrayfun(@(x) x.sidelobe_metrics.explained_energy_fraction,cases).', ...
    arrayfun(@(x) x.sidelobe_metrics.p90_outside_peak,cases).', ...
    [cases.relative_l2_to_largest].', ...
    [cases.mean_absolute_change_to_largest].', ...
    'VariableNames',{'source_count','dominant_ridge_fraction', ...
    'median_ridge_concentration','median_half_power_width_mps', ...
    'p10_dominance_margin','explained_mode_energy_fraction', ...
    'p90_outside_mode_peak','relative_l2_to_largest', ...
    'mean_absolute_change_to_largest'});

comparison_figure=plot_passive_source_convergence( ...
    results.model,results.geometry,cases,results.theory,velocity, ...
    frequency_range);
exportgraphics(comparison_figure, ...
    fullfile(output_folder,'source_convergence_600m.png'), ...
    'Resolution',180);
writetable(metrics_table, ...
    fullfile(output_folder,'source_convergence_600m.csv'));
save(fullfile(output_folder,'source_convergence_600m.mat'), ...
    'cases','metrics_table','frequency_range','-v7.3');
end

function source_index=source_index_for_case(source_count,available_source_count)
source_index=round(linspace(1,available_source_count+1,source_count+1));
source_index=source_index(1:end-1);
end
