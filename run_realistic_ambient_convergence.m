function [cases,metrics_table]=run_realistic_ambient_convergence( ...
    forward_input_file,varargin)
%RUN_REALISTIC_AMBIENT_CONVERGENCE Mixed-record passive-noise convergence.
%
% Independent stationary Gaussian source spectra are propagated through the
% saved DWM responses.  Sources are summed before any receiver correlation.

p=inputParser;
addParameter(p,'Durations',[60 600 1800], ...
    @(x) isnumeric(x) && isvector(x) && all(isfinite(x)) && all(x>0));
addParameter(p,'WindowLength',20, ...
    @(x) isscalar(x) && isfinite(x) && x>0);
addParameter(p,'SourceFrequencyBand',[1 20], ...
    @(x) isnumeric(x) && numel(x)==2 && x(1)>0 && x(1)<x(2));
addParameter(p,'SourcePsdTaperFraction',0.2, ...
    @(x) isscalar(x) && isfinite(x) && x>=0 && x<=1);
addParameter(p,'DistanceTaperFraction',0.5, ...
    @(x) isscalar(x) && isfinite(x) && x>=0 && x<=1);
addParameter(p,'Seed',314159,@(x) isscalar(x) && isfinite(x));
addParameter(p,'OutputFolder','',@(x) ischar(x) || isstring(x));
addParameter(p,'WindowBlockSize',5, ...
    @(x) isscalar(x) && x>=1 && fix(x)==x);
addParameter(p,'SourceCount',[], ...
    @(x) isempty(x) || (isscalar(x) && x>=1 && fix(x)==x));
parse(p,varargin{:});
opts=p.Results;

loaded=load(char(forward_input_file), ...
    'model','source','geometry','source_response_z');
model=loaded.model;
source=loaded.source;
geometry=loaded.geometry;
source_response=loaded.source_response_z;
clear loaded
available_source_count=size(source_response,3);
if isempty(opts.SourceCount)
    selected_source_index=1:available_source_count;
else
    if opts.SourceCount>available_source_count
        error('run_realistic_ambient_convergence:TooManySources', ...
            'SourceCount exceeds the saved response count.');
    end
    selected_source_index=round(linspace(1,available_source_count+1, ...
        opts.SourceCount+1));
    selected_source_index=selected_source_index(1:end-1);
    source_response=source_response(:,:,selected_source_index);
    geometry.sx=geometry.sx(selected_source_index);
    geometry.sy=geometry.sy(selected_source_index);
    source.number=numel(selected_source_index);
    source.Fx=source.Fx(selected_source_index);
    source.Fy=source.Fy(selected_source_index);
    source.Fz=source.Fz(selected_source_index);
    if isfield(source,'fm') && ~isscalar(source.fm)
        source.fm=source.fm(selected_source_index);
    end
end
dt=source.dt;
durations=sort(reshape(opts.Durations,1,[]));
target_window_counts=round(durations/opts.WindowLength);
if any(abs(target_window_counts*opts.WindowLength-durations)>dt)
    error('run_realistic_ambient_convergence:DurationNotWindowMultiple', ...
        'Every duration must be an integer multiple of WindowLength.');
end
if strlength(string(opts.OutputFolder))==0
    output_folder=fileparts(char(forward_input_file));
else
    output_folder=char(opts.OutputFolder);
end
if ~exist(output_folder,'dir')
    mkdir(output_folder);
end

window_samples=round(opts.WindowLength/dt);
response_samples=size(source_response,1);
receiver_count=size(source_response,2);
source_count=size(source_response,3);
if receiver_count~=numel(geometry.rx)
    error('run_realistic_ambient_convergence:GeometryMismatch', ...
        'Source responses and receiver geometry do not match.');
end
synthesis_nfft=2^nextpow2(max(window_samples,response_samples));
synthesis_frequency=(0:floor(synthesis_nfft/2))/(synthesis_nfft*dt);
frequency_index=find(synthesis_frequency>=opts.SourceFrequencyBand(1) & ...
    synthesis_frequency<=opts.SourceFrequencyBand(2) & ...
    synthesis_frequency>0 & synthesis_frequency<0.5/dt);
selected_frequency=synthesis_frequency(frequency_index);
frequency_count=numel(frequency_index);

% Store only the useful band and use single precision for this Monte Carlo
% propagation.  The subsequent correlations and dispersion are accumulated
% in double precision.
transfer_pages=complex(zeros(receiver_count,source_count, ...
    frequency_count,'single'));
source_block_size=16;
for first_source=1:source_block_size:source_count
    block_source_index=first_source:min(first_source+source_block_size-1, ...
        source_count);
    response_spectrum=fft(single(source_response(:,:,block_source_index)), ...
        synthesis_nfft,1);
    transfer_pages(:,block_source_index,:)=permute( ...
        response_spectrum(frequency_index,:,:),[2 3 1]);
end
clear source_response response_spectrum

source_psd=tukeywin(frequency_count, ...
    opts.SourcePsdTaperFraction).';
source_spectral_amplitude=sqrt(source_psd);
rng(opts.Seed,'twister');
maximum_window_count=target_window_counts(end);
cumulative_gather=[];
case_cells=cell(1,numel(durations));
case_index=1;
preview_window_count=min(target_window_counts(1), ...
    max(1,round(60/opts.WindowLength)));
preview_record=zeros(window_samples*preview_window_count, ...
    receiver_count,'single');

for first_window=1:opts.WindowBlockSize:maximum_window_count
    block_window_count=min(opts.WindowBlockSize, ...
        maximum_window_count-first_window+1);
    all_source_coefficients=complex( ...
        randn(available_source_count,block_window_count,frequency_count,'single'), ...
        randn(available_source_count,block_window_count,frequency_count,'single'))/sqrt(2);
    source_coefficients=all_source_coefficients(selected_source_index,:,:);
    source_coefficients=source_coefficients.*reshape( ...
        single(source_spectral_amplitude),1,1,[]);
    mixed_pages=pagemtimes(transfer_pages,source_coefficients);
    for local_window=1:block_window_count
        window_index=first_window+local_window-1;
        mixed_spectrum=complex(zeros(synthesis_nfft,receiver_count,'single'));
        positive_spectrum=reshape( ...
            mixed_pages(:,local_window,:),receiver_count,frequency_count).';
        mixed_spectrum(frequency_index,:)=positive_spectrum;
        mirror_index=synthesis_nfft-frequency_index+2;
        mixed_spectrum(mirror_index,:)=conj(positive_spectrum);
        mixed_record=real(ifft(mixed_spectrum,synthesis_nfft,1));
        mixed_record=mixed_record(1:window_samples,:);
        if window_index<=preview_window_count
            preview_index=(window_index-1)*window_samples+(1:window_samples);
            preview_record(preview_index,:)=mixed_record;
        end
        [window_gather,lag_time,distances,pair_counts]= ...
            compute_ncf_gather_from_traces(double(mixed_record), ...
            geometry.rx,dt,'SegmentLength',opts.WindowLength, ...
            'Overlap',0,'MaxLag',default_max_lag(model,geometry), ...
            'Normalize','spectral-whitening','Branch','symmetric', ...
            'DistanceBin',geometry.receiver_spacing, ...
            'Algorithm','linear-fft');
        if isempty(cumulative_gather)
            cumulative_gather=zeros(size(window_gather));
        end
        cumulative_gather=cumulative_gather+window_gather;
        if case_index<=numel(durations) && ...
                window_index==target_window_counts(case_index)
            averaged_gather=cumulative_gather/window_index;
            case_cells{case_index}=analyze_gather(averaged_gather,lag_time, ...
                distances,pair_counts,model,source,geometry, ...
                durations(case_index),opts.DistanceTaperFraction);
            save_case(case_cells{case_index},output_folder);
            case_index=case_index+1;
        end
    end
end

cases=[case_cells{:}];

reference_energy=cases(end).energy;
selected=cases(end).frequency>=cases(end).reliable_frequency_range_hz(1) & ...
    cases(end).frequency<=cases(end).reliable_frequency_range_hz(2);
for index=1:numel(cases)
    difference=cases(index).energy(:,selected)-reference_energy(:,selected);
    cases(index).relative_l2_to_longest=norm(difference,'fro')/ ...
        max(norm(reference_energy(:,selected),'fro'),eps);
end
metrics_table=table( ...
    [cases.duration_seconds].', ...
    target_window_counts.', ...
    arrayfun(@(x) x.image_quality_metrics.dominant_ridge_fraction,cases).', ...
    arrayfun(@(x) x.image_quality_metrics.median_ridge_concentration,cases).', ...
    arrayfun(@(x) x.image_quality_metrics.median_half_power_width_mps,cases).', ...
    arrayfun(@(x) x.image_quality_metrics.p10_dominance_margin,cases).', ...
    [cases.relative_l2_to_longest].', ...
    'VariableNames',{'duration_seconds','independent_window_count', ...
    'dominant_ridge_fraction','median_ridge_concentration', ...
    'median_half_power_width_mps','p10_dominance_margin', ...
    'relative_l2_to_longest'});

plot_cases=repmat(struct,1,numel(cases));
for index=1:numel(cases)
    plot_cases(index).energy=cases(index).energy;
    plot_cases(index).frequency=cases(index).frequency;
    plot_cases(index).title=sprintf([ ...
        '%.0f s (%d windows) | support %.1f%% | conc. %.3f | width %.0f'], ...
        cases(index).duration_seconds,target_window_counts(index), ...
        100*cases(index).image_quality_metrics.dominant_ridge_fraction, ...
        cases(index).image_quality_metrics.median_ridge_concentration, ...
        cases(index).image_quality_metrics.median_half_power_width_mps);
end
if numel(cases)==3
    comparison_figure=plot_passive_three_case_comparison( ...
        model,geometry,plot_cases,cases(end).theory,cases(end).velocity, ...
        cases(end).reliable_frequency_range_hz, ...
        'Realistic mixed ambient-noise duration convergence');
    exportgraphics(comparison_figure,fullfile(output_folder, ...
        'realistic_duration_convergence.png'),'Resolution',180);
end
writetable(metrics_table,fullfile(output_folder, ...
    'realistic_duration_convergence.csv'));
simulation_metadata=struct( ...
    'source_mixing','all sources summed before receiver correlation', ...
    'source_process','independent stationary complex Gaussian spectra', ...
    'source_frequency_hz',selected_frequency, ...
    'source_psd',source_psd, ...
    'window_length_seconds',opts.WindowLength, ...
    'source_index',selected_source_index, ...
    'source_count',source_count, ...
    'seed',opts.Seed, ...
    'processing_normalization','spectral-whitening');
save(fullfile(output_folder,'realistic_duration_convergence.mat'), ...
    'cases','metrics_table','simulation_metadata','-v7.3');
preview_time=(0:size(preview_record,1)-1)'*dt;
save(fullfile(output_folder,'realistic_stationary_preview_60s.mat'), ...
    'preview_record','preview_time','simulation_metadata','-v7.3');
end

function max_lag=default_max_lag(model,geometry)
aperture=max(geometry.rx)-min(geometry.rx);
max_lag=1.3*aperture/(0.90*min(model.vs));
end

function results=analyze_gather(gather,lag_time,distances,pair_counts, ...
    model,source,geometry,duration,distance_taper_fraction)
dt=source.dt;
source.recordlength=duration;
velocity=(150:2:500)';
minimum_phase_velocity=0.90*min(model.vs);
spatial_alias_limit=minimum_phase_velocity/(2*geometry.receiver_spacing);
dispersion_fmax=min(source.maxfre,0.95*spatial_alias_limit);
[energy,frequency]=surface_wave_dispersion( ...
    gather,distances,dt,velocity,dispersion_fmax, ...
    'Method','phase','Component','vertical','FrequencyMin',1, ...
    'ZeroPadding',8,'DistanceTaperFraction',distance_taper_fraction, ...
    'Plot',false);
aperture=max(geometry.rx)-min(geometry.rx);
aperture_frequency_floor=3*max(model.vs)/aperture;
frequency_range=[max(source.fmin,aperture_frequency_floor), ...
    dispersion_fmax];
picks=pick_dispersion_ridge(energy,frequency,velocity, ...
    'FrequencyRange',frequency_range,'VelocityRange',[170 460], ...
    'Smoothness',0.35,'MaxJump',30,'MinimumEnergy',0.05);
theory=compute_theoretical_dispersion(model,frequency, ...
    'RayleighModes',4,'LoveModes',4);
image_quality_metrics=dispersion_image_quality_metrics( ...
    energy,frequency,velocity,theory.frequency,theory.rayleigh(:,1), ...
    'FrequencyRange',frequency_range);
continuity_metrics=dispersion_continuity_metrics( ...
    energy,frequency,velocity,theory.frequency,theory.rayleigh(:,1), ...
    'FrequencyRange',frequency_range);
sidelobe_metrics=dispersion_sidelobe_metrics( ...
    energy,frequency,velocity,theory.frequency,theory.rayleigh, ...
    'FrequencyRange',frequency_range,'ModeTolerance',15);
results=struct('model',model,'source',source,'geometry',geometry, ...
    'ncf_gather',gather,'lag_time',lag_time,'distances',distances, ...
    'pair_counts',pair_counts,'energy',energy,'frequency',frequency, ...
    'velocity',velocity,'picks',picks,'theory',theory, ...
    'dispersion_method','phase', ...
    'distance_taper_fraction',distance_taper_fraction, ...
    'correlation_mode','mixed finite-record', ...
    'duration_seconds',duration,'max_lag',default_max_lag(model,geometry), ...
    'segment_length',20,'overlap',0, ...
    'normalization','spectral-whitening', ...
    'reliable_frequency_range_hz',frequency_range, ...
    'spatial_alias_limit_hz',spatial_alias_limit, ...
    'aperture_frequency_floor_hz',aperture_frequency_floor, ...
    'image_quality_metrics',image_quality_metrics, ...
    'continuity_metrics',continuity_metrics, ...
    'sidelobe_metrics',sidelobe_metrics);
end

function save_case(results,output_folder)
tag=sprintf('realistic_stationary_%04ds',round(results.duration_seconds));
save(fullfile(output_folder,[tag,'_results.mat']),'results','-v7.3');
writetable(results.picks,fullfile(output_folder, ...
    [tag,'_picked_rayleigh.csv']));
summary_figure=plot_passive_surface_wave_summary(results);
exportgraphics(summary_figure,fullfile(output_folder,[tag,'.png']), ...
    'Resolution',180);
end
