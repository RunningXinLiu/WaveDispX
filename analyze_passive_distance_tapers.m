function [cases,metrics_table]=analyze_passive_distance_tapers( ...
    results_input,taper_fractions,varargin)
%ANALYZE_PASSIVE_DISTANCE_TAPERS Test spatial-window sidelobe tradeoffs.

p=inputParser;
addParameter(p,'OutputFolder','',@(x) ischar(x) || isstring(x));
addParameter(p,'ModeTolerance',15, ...
    @(x) isscalar(x) && isfinite(x) && x>0);
parse(p,varargin{:});
opts=p.Results;

if ischar(results_input) || isstring(results_input)
    loaded=load(char(results_input),'results');
    results=loaded.results;
else
    results=results_input;
end
taper_fractions=reshape(taper_fractions,1,[]);
if any(taper_fractions<0 | taper_fractions>1) || ...
        any(diff(taper_fractions)<=0)
    error('analyze_passive_distance_tapers:InvalidTapers', ...
        'Taper fractions must increase from zero to one.');
end
if strlength(string(opts.OutputFolder))==0
    output_folder=results.output_folder;
else
    output_folder=char(opts.OutputFolder);
end

velocity=results.velocity;
frequency_range=results.reliable_frequency_range_hz;
dispersion_fmax=min(results.source.maxfre, ...
    0.95*results.spatial_alias_limit_hz);
cases=repmat(struct,1,numel(taper_fractions));
for case_index=1:numel(taper_fractions)
    taper_fraction=taper_fractions(case_index);
    [energy,frequency]=surface_wave_dispersion( ...
        results.ncf_gather,results.distances,results.source.dt, ...
        velocity,dispersion_fmax,'Method','phase', ...
        'Component','vertical','FrequencyMin',1,'ZeroPadding',8, ...
        'DistanceTaperFraction',taper_fraction,'Plot',false);
    image_metrics=dispersion_image_quality_metrics( ...
        energy,frequency,velocity,results.theory.frequency, ...
        results.theory.rayleigh(:,1),'FrequencyRange',frequency_range);
    sidelobe_metrics=dispersion_sidelobe_metrics( ...
        energy,frequency,velocity,results.theory.frequency, ...
        results.theory.rayleigh,'FrequencyRange',frequency_range, ...
        'ModeTolerance',opts.ModeTolerance);
    cases(case_index).taper_fraction=taper_fraction;
    cases(case_index).energy=energy;
    cases(case_index).frequency=frequency;
    cases(case_index).metrics=image_metrics;
    cases(case_index).sidelobe_metrics=sidelobe_metrics;
    cases(case_index).title=sprintf([ ...
        'Tukey %.2f | support %.1f%% | width %.0f | outside P90 %.3f'], ...
        taper_fraction,100*image_metrics.dominant_ridge_fraction, ...
        image_metrics.median_half_power_width_mps, ...
        sidelobe_metrics.p90_outside_peak);
end

metrics_table=table( ...
    [cases.taper_fraction].', ...
    arrayfun(@(x) x.metrics.dominant_ridge_fraction,cases).', ...
    arrayfun(@(x) x.metrics.median_ridge_concentration,cases).', ...
    arrayfun(@(x) x.metrics.median_half_power_width_mps,cases).', ...
    arrayfun(@(x) x.metrics.p10_dominance_margin,cases).', ...
    arrayfun(@(x) x.sidelobe_metrics.explained_energy_fraction,cases).', ...
    arrayfun(@(x) x.sidelobe_metrics.p90_outside_peak,cases).', ...
    arrayfun(@(x) x.sidelobe_metrics.unexplained_hot_pixel_fraction,cases).', ...
    'VariableNames',{'taper_fraction','dominant_ridge_fraction', ...
    'median_ridge_concentration','median_half_power_width_mps', ...
    'p10_dominance_margin','explained_mode_energy_fraction', ...
    'p90_outside_mode_peak','unexplained_hot_pixel_fraction'});

if numel(cases)<3
    error('analyze_passive_distance_tapers:TooFewPlotCases', ...
        'At least three taper fractions are required for comparison.');
end
plot_index=unique(round(linspace(1,numel(cases),3)),'stable');
comparison_figure=plot_passive_three_case_comparison( ...
    results.model,results.geometry,cases(plot_index),results.theory, ...
    velocity,frequency_range, ...
    'Phase-shift distance-taper comparison on the 600 m array');
exportgraphics(comparison_figure, ...
    fullfile(output_folder,'distance_taper_comparison_600m.png'), ...
    'Resolution',180);
writetable(metrics_table, ...
    fullfile(output_folder,'distance_taper_comparison_600m.csv'));
save(fullfile(output_folder,'distance_taper_comparison_600m.mat'), ...
    'cases','metrics_table','frequency_range','-v7.3');
end
