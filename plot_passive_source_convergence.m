function fig=plot_passive_source_convergence(model,geometry,cases, ...
    theory,velocity,frequency_range)
%PLOT_PASSIVE_SOURCE_CONVERGENCE Compare dispersion as source count grows.

fig=figure('Position',[50 50 1700 950]);
layout=tiledlayout(fig,2,3,'TileSpacing','compact','Padding','compact');
velocity_axes=nexttile(layout,1);
density_axes=nexttile(layout,2);
plot_layer_model(velocity_axes,density_axes,model);
geometry_axes=nexttile(layout,3);
plot_source_receiver_geometry(geometry_axes,geometry.sx,geometry.sy, ...
    geometry.rx,geometry.ry,'Title',sprintf( ...
    '%d-source stratified geometry',numel(geometry.sx)));

for case_index=1:numel(cases)
    ax=nexttile(layout,3+case_index);
    imagesc(ax,cases(case_index).frequency,velocity, ...
        cases(case_index).energy);
    axis(ax,'xy');
    hold(ax,'on');
    plot(ax,theory.frequency,theory.rayleigh(:,2:end), ...
        'w:','LineWidth',1.0);
    plot(ax,theory.frequency,theory.rayleigh(:,1), ...
        'w--','LineWidth',1.4);
    xlim(ax,frequency_range);
    ylim(ax,[min(velocity) max(velocity)]);
    clim(ax,[0 1]);
    xlabel(ax,'Frequency (Hz)');
    ylabel(ax,'Phase velocity (m/s)');
    if isfield(cases(case_index),'sidelobe_metrics')
        title_text=sprintf([ ...
            'N=%d | support %.1f%% | conc. %.3f | width %.0f | outside P90 %.3f'], ...
            cases(case_index).source_count, ...
            100*cases(case_index).metrics.dominant_ridge_fraction, ...
            cases(case_index).metrics.median_ridge_concentration, ...
            cases(case_index).metrics.median_half_power_width_mps, ...
            cases(case_index).sidelobe_metrics.p90_outside_peak);
    else
        title_text=sprintf([ ...
            'N=%d | support %.1f%% | concentration %.3f | width %.0f m/s'], ...
            cases(case_index).source_count, ...
            100*cases(case_index).metrics.dominant_ridge_fraction, ...
            cases(case_index).metrics.median_ridge_concentration, ...
            cases(case_index).metrics.median_half_power_width_mps);
    end
    title(ax,title_text);
    colormap(ax,turbo);
end
sgtitle(layout,'Passive-source convergence with identical model and source spectrum');
end
