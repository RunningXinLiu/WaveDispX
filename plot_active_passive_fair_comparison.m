function [fig,metrics_table]=plot_active_passive_fair_comparison( ...
    active_result_file,passive_output_folder,varargin)
%PLOT_ACTIVE_PASSIVE_FAIR_COMPARISON Compare a common frequency band.

p=inputParser;
addParameter(p,'FrequencyRange',[5 18.8], ...
    @(x) isnumeric(x) && numel(x)==2 && x(1)<x(2));
addParameter(p,'OutputFile','',@(x) ischar(x) || isstring(x));
parse(p,varargin{:});
frequency_range=p.Results.FrequencyRange;

active=load(char(active_result_file), ...
    'model','source','p1','f1','vr');
durations=[60 600 1800];
passive=cell(1,numel(durations));
for index=1:numel(durations)
    loaded=load(fullfile(passive_output_folder,sprintf( ...
        'realistic_stationary_%04ds_results.mat',durations(index))), ...
        'results');
    passive{index}=loaded.results;
end

active_velocity=(100:500)';
active_metrics=dispersion_image_quality_metrics( ...
    active.p1,active.f1,active_velocity,active.vr(:,1),active.vr(:,2), ...
    'FrequencyRange',frequency_range);
passive_metrics=cellfun(@(x) dispersion_image_quality_metrics( ...
    x.energy,x.frequency,x.velocity,x.theory.frequency, ...
    x.theory.rayleigh(:,1),'FrequencyRange',frequency_range), ...
    passive,'UniformOutput',false);

fig=figure('Position',[30 40 2100 980]);
layout=tiledlayout(fig,2,4,'TileSpacing','compact','Padding','compact');
velocity_axes=nexttile(layout,1);
density_axes=nexttile(layout,2);
plot_layer_model(velocity_axes,density_axes,active.model);
active_geometry_axes=nexttile(layout,3);
plot_source_receiver_geometry(active_geometry_axes,0,0, ...
    active.source.offset,zeros(size(active.source.offset)), ...
    'Title','Active geometry: 1 source, 200 receivers, 1 m spacing');
passive_geometry_axes=nexttile(layout,4);
plot_source_receiver_geometry(passive_geometry_axes, ...
    passive{end}.geometry.sx,passive{end}.geometry.sy, ...
    passive{end}.geometry.rx,passive{end}.geometry.ry, ...
    'Title','Passive geometry: 384 sources, 121 receivers, 5 m spacing');

active_axes=nexttile(layout,5);
plot_energy(active_axes,active.f1,active_velocity,active.p1, ...
    active.vr(:,1),active.vr(:,2:end),frequency_range,sprintf( ...
    'Active, Hankel | support %.1f%% | conc. %.3f | width %.0f', ...
    100*active_metrics.dominant_ridge_fraction, ...
    active_metrics.median_ridge_concentration, ...
    active_metrics.median_half_power_width_mps));
for index=1:numel(passive)
    ax=nexttile(layout,5+index);
    result=passive{index};
    metrics=passive_metrics{index};
    plot_energy(ax,result.frequency,result.velocity,result.energy, ...
        result.theory.frequency,result.theory.rayleigh, ...
        frequency_range,sprintf([ ...
        'Passive %.0f s, phase | support %.1f%% | conc. %.3f | width %.0f'], ...
        durations(index),100*metrics.dominant_ridge_fraction, ...
        metrics.median_ridge_concentration, ...
        metrics.median_half_power_width_mps));
end
sgtitle(layout,'Active/passive comparison on the identical 5--18.8 Hz band');

metrics_table=table( ...
    ["active";"passive";"passive";"passive"], ...
    [nan;durations.'], ...
    [active_metrics.dominant_ridge_fraction; ...
     cellfun(@(x) x.dominant_ridge_fraction,passive_metrics).'], ...
    [active_metrics.median_ridge_concentration; ...
     cellfun(@(x) x.median_ridge_concentration,passive_metrics).'], ...
    [active_metrics.median_half_power_width_mps; ...
     cellfun(@(x) x.median_half_power_width_mps,passive_metrics).'], ...
    'VariableNames',{'data_type','duration_seconds', ...
    'dominant_ridge_fraction','median_ridge_concentration', ...
    'median_half_power_width_mps'});
if strlength(string(p.Results.OutputFile))>0
    output_file=char(p.Results.OutputFile);
    exportgraphics(fig,output_file,'Resolution',180);
    [folder,name]=fileparts(output_file);
    writetable(metrics_table,fullfile(folder,[name,'.csv']));
end
end

function plot_energy(ax,frequency,velocity,energy,theory_frequency, ...
    theory_velocity,frequency_range,title_text)
imagesc(ax,frequency,velocity,energy);
axis(ax,'xy');
hold(ax,'on');
plot(ax,theory_frequency,theory_velocity,'w:','LineWidth',1.0);
xlim(ax,frequency_range);
ylim(ax,[150 500]);
clim(ax,[0 1]);
xlabel(ax,'Frequency (Hz)');
ylabel(ax,'Phase velocity (m/s)');
title(ax,title_text);
colormap(ax,turbo);
end
