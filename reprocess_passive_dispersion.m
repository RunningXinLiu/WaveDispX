function results=reprocess_passive_dispersion(results_input,varargin)
%REPROCESS_PASSIVE_DISPERSION Reimage a saved passive NCF without forwarding.

p=inputParser;
addParameter(p,'DistanceTaperFraction',0.5, ...
    @(x) isscalar(x) && isfinite(x) && x>=0 && x<=1);
addParameter(p,'OutputFolder','',@(x) ischar(x) || isstring(x));
parse(p,varargin{:});
opts=p.Results;

if ischar(results_input) || isstring(results_input)
    loaded=load(char(results_input),'results');
    results=loaded.results;
else
    results=results_input;
end
if strlength(string(opts.OutputFolder))==0
    output_folder=results.output_folder;
else
    output_folder=char(opts.OutputFolder);
end

dispersion_fmax=min(results.source.maxfre, ...
    0.95*results.spatial_alias_limit_hz);
[results.energy,results.frequency]=surface_wave_dispersion( ...
    results.ncf_gather,results.distances,results.source.dt, ...
    results.velocity,dispersion_fmax,'Method','phase', ...
    'Component','vertical','FrequencyMin',1,'ZeroPadding',8, ...
    'DistanceTaperFraction',opts.DistanceTaperFraction,'Plot',false);
results.picks=pick_dispersion_ridge( ...
    results.energy,results.frequency,results.velocity, ...
    'FrequencyRange',results.reliable_frequency_range_hz, ...
    'VelocityRange',[170 460],'Smoothness',0.35, ...
    'MaxJump',30,'MinimumEnergy',0.05);
results.theory=compute_theoretical_dispersion( ...
    results.model,results.frequency,'RayleighModes',4,'LoveModes',4);
results.continuity_metrics=dispersion_continuity_metrics( ...
    results.energy,results.frequency,results.velocity, ...
    results.theory.frequency,results.theory.rayleigh(:,1), ...
    'FrequencyRange',results.reliable_frequency_range_hz);
results.image_quality_metrics=dispersion_image_quality_metrics( ...
    results.energy,results.frequency,results.velocity, ...
    results.theory.frequency,results.theory.rayleigh(:,1), ...
    'FrequencyRange',results.reliable_frequency_range_hz);
results.sidelobe_metrics=dispersion_sidelobe_metrics( ...
    results.energy,results.frequency,results.velocity, ...
    results.theory.frequency,results.theory.rayleigh, ...
    'FrequencyRange',results.reliable_frequency_range_hz, ...
    'ModeTolerance',15);
results.distance_taper_fraction=opts.DistanceTaperFraction;

tag=sprintf('tukey_%03d',round(100*opts.DistanceTaperFraction));
summary_figure=plot_passive_surface_wave_summary(results);
exportgraphics(summary_figure,fullfile(output_folder, ...
    ['passive_end_to_end_',tag,'.png']),'Resolution',180);
writetable(results.picks,fullfile(output_folder, ...
    ['picked_rayleigh_',tag,'.csv']));

heavy_fields={'traces','single_source','ensemble_cross_spectrum', ...
    'mixed_ncf_gather','mixed_lag_time','mixed_distances', ...
    'mixed_pair_counts'};
heavy_fields=heavy_fields(isfield(results,heavy_fields));
compact_results=rmfield(results,heavy_fields);
save(fullfile(output_folder, ...
    ['passive_dispersion_',tag,'_results.mat']), ...
    'compact_results','-v7.3');
end
